#!/usr/bin/env node
/**
 * tools/gen-burn-rules.mjs
 *
 * Compile a pack's `spec.policy` (multi-window burn-rate alerts, forecasts) and the error-budget
 * recording rules into a Prometheus rule file, with the PromQL forms that survived a live queue
 * manager (see tools/lib/burn-rules.mjs for the five measured deviations from compile.mjs).
 *
 * Usage:
 *   node tools/gen-burn-rules.mjs --pack reference-packs/grafana.pack.yaml [--out <file>]
 *                                 [--step <seconds>] [--lab] [--pack-snippet]
 *
 *   --out          default <pack directory>/rules/<name>.burn.yml
 *   --step         seconds between samples (default: the pack's smallest scrape_interval, else 30)
 *   --lab          lab `for:` durations (30 s / 2 m / 5 m) instead of production (2 m / 5 m / 10 m)
 *   --pack-snippet print the generated recording rules as a `spec.queries.recording_rules` block
 *                  instead of writing the file (packs that materialise them declare them verbatim)
 *   PACK           environment variable, same as --pack
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { parse as parseYaml } from './lib/mini-yaml.mjs';
import { compileBurnRules, toYaml, packSnippet } from './lib/burn-rules.mjs';

const argv = process.argv.slice(2);
const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
const packPath = opt('--pack') || process.env.PACK;
if (!packPath) { console.error('usage: gen-burn-rules.mjs --pack <pack.yaml> [--out <file>] [--step <seconds>] [--lab] [--pack-snippet]'); process.exit(2); }
const pack = parseYaml(readFileSync(resolve(packPath), 'utf8'));
const out = resolve(opt('--out') || resolve(dirname(resolve(packPath)), 'rules', `${pack.metadata.name}.burn.yml`));
const r = compileBurnRules(pack, { step: opt('--step') ? Number(opt('--step')) : undefined, lab: argv.includes('--lab') });
for (const w of r.warnings) console.error(`warning: ${w}`);
if (argv.includes('--pack-snippet')) { console.log(packSnippet(r.recording)); process.exit(0); }
const header = [
  `# GENERATED by tools/gen-burn-rules.mjs from ${packPath} (spec.policy) — do not edit.`,
  '# Multi-window burn-rate alerts (one per declared window), forecast alerts and the',
  '# error-budget recording rules. Names/labels follow compile.mjs; tools/lib/burn-rules.mjs',
  `# lists the five PromQL deviations. Sample step ${r.step}s, for: ${argv.includes('--lab') ? 'lab' : 'production'}.`,
  '',
];
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, toYaml(r.groups, header));
console.log(`${out}: ${r.recording.length} recording rules, ${r.burnCount} burn-rate alerts, ${r.forecasts.length} forecast alerts (step ${r.step}s${r.warnings.length ? `, ${r.warnings.length} warning(s)` : ''})`);
